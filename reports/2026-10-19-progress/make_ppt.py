def _run(p, text, size, color=NAVY, bold=False):
    r = p.add_run()
    r.text = text
    r.font.size, r.font.bold, r.font.name = Pt(size), bold, FONT
    r.font.color.rgb = color
    return r


def _rich(p, text, size, color=NAVY):
    """**粗体** 标记转为加粗红字。"""
    for i, part in enumerate(text.split("**")):
        if part:
            _run(p, part, size, ACCENT if i % 2 else color, bold=bool(i % 2))


def notes(s, text):
    s.notes_slide.notes_text_frame.text = text.strip()


def slide(title, subtitle=None, talk=None):
    s = prs.slides.add_slide(BLANK)
    if talk:
        notes(s, talk)
    bar = s.shapes.add_shape(1, 0, 0, W, Emu(80000))
    bar.fill.solid()
    bar.fill.fore_color.rgb = ACCENT
    bar.line.fill.background()
    tb = s.shapes.add_textbox(Emu(500000), Emu(220000), W - Emu(1000000), Emu(700000))
    _run(tb.text_frame.paragraphs[0], title, 28, bold=True)
    if subtitle:
        p = tb.text_frame.add_paragraph()
        _run(p, subtitle, 14, GREY)
    n = len(prs.slides)
    ft = s.shapes.add_textbox(W - Emu(1500000), H - Emu(450000), Emu(1200000), Emu(300000))
    _run(ft.text_frame.paragraphs[0], f"SciTeam · {n}", 10, GREY)
    return s


def bullets(s, items, x=500000, y=1250000, w=None, h=None, size=17):
    w = w or (W - Emu(1000000))
    h = h or (H - Emu(1800000))
    tb = s.shapes.add_textbox(Emu(x), Emu(y), w, h)
    tf = tb.text_frame
    tf.word_wrap = True
    first = True
    for it in items:
        level = 0
        while it.startswith("  "):
            level, it = level + 1, it[2:]
        p = tf.paragraphs[0] if first else tf.add_paragraph()
        first = False
        p.space_after = Pt(6)
        prefix = "• " if level == 0 else "– "
        _run(p, "    " * level + prefix, size - 2 * level, GREY)
        _rich(p, it, size - 2 * level, NAVY if level == 0 else GREY)
    return tb


def table(s, rows, x=500000, y=1300000, w=None, row_h=380000, size=13, col_w=None):
    w = w or (W - Emu(1000000))
    shp = s.shapes.add_table(len(rows), len(rows[0]), Emu(x), Emu(y), w, Emu(row_h * len(rows)))
    t = shp.table
    if col_w:
        tot = sum(col_w)
        for i, cw in enumerate(col_w):
            t.columns[i].width = Emu(int(w * cw / tot))
    for r, row in enumerate(rows):
        for c, val in enumerate(row):
            cell = t.cell(r, c)
            cell.text = ""
            p = cell.text_frame.paragraphs[0]
            if r == 0:
                _run(p, str(val), size, RGBColor(0xFF, 0xFF, 0xFF), bold=True)
                cell.fill.solid()
                cell.fill.fore_color.rgb = NAVY
            else:
                _rich(p, str(val), size)
                cell.fill.solid()
                cell.fill.fore_color.rgb = LIGHT if r % 2 else RGBColor(0xFF, 0xFF, 0xFF)
    return t


def bar_chart(s, cats, series, x, y, w, h, title=None, pct=True):
    cd = CategoryChartData()
    cd.categories = cats
    for name, vals in series:
        cd.add_series(name, vals)
    gf = s.shapes.add_chart(XL_CHART_TYPE.COLUMN_CLUSTERED, Emu(x), Emu(y), Emu(w), Emu(h), cd)
    ch = gf.chart
    ch.has_legend = len(series) > 1
    if ch.has_legend:
        ch.legend.position = XL_LEGEND_POSITION.BOTTOM
        ch.legend.include_in_layout = False
        ch.legend.font.size, ch.legend.font.name = Pt(12), FONT
    plot = ch.plots[0]
    plot.has_data_labels = True
    dl = plot.data_labels
    dl.font.size, dl.font.name = Pt(11), FONT
    dl.number_format = "0%" if pct else "0.000"
    dl.number_format_is_linked = False
    ch.category_axis.tick_labels.font.size = Pt(12)
    ch.category_axis.tick_labels.font.name = FONT
    ch.value_axis.tick_labels.font.size = Pt(10)
    ch.value_axis.has_major_gridlines = False
    if pct:
        ch.value_axis.tick_labels.number_format = "0%"
        ch.value_axis.tick_labels.number_format_is_linked = False
    if title:
        ch.has_title = True
        ch.chart_title.text_frame.text = title
        f = ch.chart_title.text_frame.paragraphs[0].runs[0].font
        f.size, f.name, f.bold = Pt(14), FONT, True
    palette = [NAVY, ACCENT, RGBColor(0x7F, 0x8C, 0x8D), RGBColor(0x27, 0xAE, 0x60)]
    for i, ser in enumerate(plot.series):
        ser.format.fill.solid()
        ser.format.fill.fore_color.rgb = palette[i % len(palette)]
    return ch


