"""Derive the X-evid taskset from the SciCode taskset (docs/60-experiment.md §6.6 v2).

Same problems, seeds and images. Changed: the grader scores the two private solutions
(bench/xevid/grade_run.py), the brief asks for private solutions, and the harness patches cover
both implementers' harness files. Run after editing scicode-verified.yaml or this script.

Usage: make_taskset.py [--out configs/tasksets/xevid-scicode.yaml]
"""

import argparse
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[2]
SRC = ROOT / "configs/tasksets/scicode-verified.yaml"

BRIEF = (
    "Solve the scientific computing problem in /workspace/PROBLEM.md. Implement every function "
    "listed there, keeping each function's name and signature, in your private file "
    "/private/<your id>/solution.py (the /workspace directory is read-only for you). Another "
    "implementer is solving the same problem independently and cannot see your work. Your goal "
    "is accepted only when an automatic validator finds that your solution and theirs agree on "
    "every checkable test input. Physical conventions, units and edge cases matter. Keep "
    "solution.py importable: no top-level computation, no printing, no plotting. The environment "
    "has numpy, scipy, sympy and matplotlib installed (no network, do not install packages). I am "
    "not available during the run; decide everything yourselves."
)


def build(src: Path = SRC) -> dict:
    ts = yaml.safe_load(src.read_text())
    ts["name"] = "xevid-scicode"
    ts["grader"] = ".venv/bin/python bench/xevid/grade_run.py {task.pid} {workspace} --json {out}"
    ts["vars"]["brief"] = BRIEF
    patches = ts["patches"]
    patches.pop("runtime/default.yaml", None)          # the X-evid runtime file sets its image
    patches["harness/team-xevid-b.yaml"] = dict(patches["harness/team-institution.yaml"])
    ts["identity"] = {
        "grader": "sha256sum bench/xevid/grade_run.py bench/scicode/grade.py",
        "validator": "sha256sum bench/xevid/agree.py bench/xevid/bundles/{task.pid}/bundle.json",
        "dataset": ts["identity"]["dataset"],
    }
    return ts


def main(argv: list[str] | None = None) -> None:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--out", type=Path, default=ROOT / "configs/tasksets/xevid-scicode.yaml")
    a = ap.parse_args(argv)
    body = yaml.safe_dump(build(), sort_keys=False, width=100, allow_unicode=True)
    a.out.write_text("# Generated by bench/xevid/make_taskset.py from scicode-verified.yaml "
                     "(docs/60 §6.6 v2); do not edit.\n" + body)
    print(f"wrote {a.out}")


if __name__ == "__main__":
    main()
