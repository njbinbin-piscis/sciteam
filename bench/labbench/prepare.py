"""Prepare the LAB-Bench screening panel for the experiment runner (docs/60 §4.4.1).

  data/seqqa_panel.jsonl                 from build.py (originals + perturbed twins)
  data/panel.jsonl, data/keys.json       + ProtocolQA sample (options shuffled, not perturbed)
  seeds/<item>/PROBLEM.md                what the agent sees (no key)
  configs/tasksets/labbench-panel.yaml   generated task set

Usage (repo root, venv active): python bench/labbench/prepare.py [--protocol-n 16 --seed 7]
"""

from __future__ import annotations

import argparse
import json
import random
from pathlib import Path

import pandas as pd
import yaml

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent.parent
DATA = HERE / "data"
SEEDS = HERE / "seeds"
UP = HERE / "upstream"
TASKSET = ROOT / "configs" / "tasksets" / "labbench-panel.yaml"
IMAGE = "sciteam-sci:v0"
INSUFFICIENT = "Insufficient information to answer the question."
LETTERS = "ABCDEFGH"

BRIEF = (
    "Answer the multiple-choice question in /workspace/PROBLEM.md. Write only the letter of your "
    "chosen option to /workspace/ANSWER.txt (for example: C). If the information given is not enough "
    "to decide, choose the option that says so; a wrong answer is worse than admitting that. You "
    "may compute with Python (numpy, scipy, sympy are installed; no network, do not install "
    "packages). I am not available during the run; decide everything yourselves."
)


def protocol_items(n: int, seed: int) -> list[dict]:
    rng = random.Random(seed)
    df = pd.read_parquet(UP / "ProtocolQA.parquet")
    rows = [r for _, r in df.iterrows()]
    out = []
    for k, r in enumerate(rng.sample(rows, n)):
        opts = [r.ideal.strip(), *[d.strip() for d in r.distractors], INSUFFICIENT]
        rng.shuffle(opts)
        out.append({
            "id": f"protocolqa-{k}-orig", "subtask": "protocolqa-v1-public", "variant": "unperturbed",
            "source_id": r.id, "question": f"Protocol:\n\n{r.protocol.strip()}\n\nQuestion: {r.question.strip()}",
            "options": {LETTERS[i]: o for i, o in enumerate(opts)},
            "answer": LETTERS[opts.index(r.ideal.strip())],
            "insufficient": LETTERS[opts.index(INSUFFICIENT)],
        })
    return out


def problem_md(it: dict) -> str:
    opts = "\n".join(f"{k}. {v}" for k, v in it["options"].items())
    return f"# Question\n\n{it['question']}\n\n# Options\n\n{opts}\n"


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--protocol-n", type=int, default=16)
    ap.add_argument("--seed", type=int, default=7)
    a = ap.parse_args()
    items = [json.loads(ln) for ln in (DATA / "seqqa_panel.jsonl").read_text().splitlines()]
    items += protocol_items(a.protocol_n, a.seed)
    (DATA / "panel.jsonl").write_text("".join(json.dumps(x, ensure_ascii=False) + "\n" for x in items))
    keys = {x["id"]: {"answer": x["answer"], "insufficient": x["insufficient"], "subtask": x["subtask"],
                      "variant": x["variant"], "source_id": x["source_id"]} for x in items}
    (DATA / "keys.json").write_text(json.dumps(keys, indent=1))
    tasks = []
    for x in items:
        d = SEEDS / x["id"]
        d.mkdir(parents=True, exist_ok=True)
        (d / "PROBLEM.md").write_text(problem_md(x))
        tasks.append({"id": x["id"], "vars": {"item": x["id"], "seed": str(d), "image": IMAGE}})
    budget = {"cost_usd": 3, "wall_clock_s": 1800, "max_steps": 200}
    ts = {
        "name": "labbench-panel",
        "grader": ".venv/bin/python bench/labbench/grade.py {task.item} {workspace} --json {out}",
        "vars": {"brief": BRIEF},
        "patches": {
            "runtime/default.yaml": {"sandbox": {"image": IMAGE}, "budget": {"cost_usd": 20, "wall_clock_s": 3600}},
            "harness/team-default.yaml": {"budget": budget},
        },
        "identity": {
            "grader": "sha256sum bench/labbench/grade.py",
            "dataset": "sha256sum bench/labbench/upstream/SeqQA.parquet bench/labbench/upstream/ProtocolQA.parquet",
            "panel": "sha256sum bench/labbench/data/panel.jsonl bench/labbench/data/keys.json",
            "builder": "sha256sum bench/labbench/build.py bench/labbench/solve.py bench/labbench/prepare.py",
            "sandbox_image": "docker image inspect -f '{{.Id}}' " + IMAGE,
            "seed": "cd {task.seed} && sha256sum PROBLEM.md",
        },
        "tasks": tasks,
    }
    TASKSET.write_text("# Generated by bench/labbench/prepare.py (docs/60 §4.4.1); do not edit.\n"
                       + yaml.safe_dump(ts, sort_keys=False, width=100, allow_unicode=True))
    print(f"{len(items)} items, taskset -> {TASKSET}")


if __name__ == "__main__":
    main()
